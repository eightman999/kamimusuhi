def atomic_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + f".{os.getpid()}.tmp")
    temp.write_text(json.dumps(value, allow_nan=False, indent=2))
    os.replace(temp, path)


def fraction(numerator, denominator):
    return float(numerator / denominator) if denominator else None


def action_metrics(actions, references):
    flat_a, flat_r = actions.long().flatten().cpu(), references.long().flatten().cpu()
    confusion = torch.bincount(flat_r * 6 + flat_a, minlength=36).reshape(6, 6).double()
    tp = confusion.diag()
    precision = torch.where(confusion.sum(0) > 0, tp / confusion.sum(0).clamp_min(1), 0)
    recall = torch.where(confusion.sum(1) > 0, tp / confusion.sum(1).clamp_min(1), 0)
    f1 = torch.where(precision+recall > 0, 2*precision*recall/(precision+recall).clamp_min(1e-12), 0)
    distribution = torch.bincount(flat_a, minlength=6).double()/max(1, flat_a.numel())
    entropy = -(distribution * distribution.clamp_min(1e-12).log()).sum()
    return {"confusion_matrix": confusion.long().tolist(), "per_action_precision": precision.tolist(),
            "per_action_recall": recall.tolist(), "per_action_f1": f1.tolist(),
            "action_macro_f1": float(f1.mean()), "action_entropy_nats": float(entropy),
            "action_distribution": distribution.tolist(), "orient_rate": float(distribution[2]),
            "observe_rate": float(distribution[3]), "recall_rate": float(distribution[4]),
            "language_action_rate": float(distribution[5])}


def transform_observation(obs, mode, t, horizon, generator, permutation, previous):
    result = obs.clone()
    if mode == "channel_shuffle":
        result[:, :11] = result[:, permutation]
    elif mode == "time_shuffle":
        # Fixed random permutation of prior available observations: no future leakage.
        if previous:
            index = int(torch.randint(len(previous), (1,), generator=generator))
            result = previous[index].clone()
    elif mode and mode.startswith("mask_"):
        result[:, int(mode.split("_")[-1])] = 0
    elif mode == "cue_mask" and t == 0:
        result[:, :11] = 0
    elif mode == "latent_correlated_removal":
        result[:, [0, 1, 2, 3, 4, 5, 6, 9]] = 0
    elif mode == "prefix_removal" and t < max(1, horizon//4):
        result[:, :14] = 0
    elif mode == "suffix_removal" and t >= horizon*3//4:
        result[:, :14] = 0
    return result


def matched_schedule(learned_trace, seed):
    """Exactly match accepted call count; randomize episode assignment and time."""
    accepted = learned_trace["accepted_calls"].bool()
    count = int(accepted.any(0).sum())
    horizon, n_envs = accepted.shape
    generator = torch.Generator().manual_seed(seed)
    schedule = torch.zeros((horizon, n_envs), dtype=torch.bool)
    selected = torch.randperm(n_envs, generator=generator)[:count]
    times = torch.randint(max(1, horizon-1), (count,), generator=generator)
    schedule[times, selected] = True
    return schedule


@torch.no_grad()
def evaluate_episode(model, config, n_envs=256, seed=900001, gate="learned", response_mode=None,
                     state_mode="normal", sensing=None, shortcut=None, call_schedule=None,
                     device="cpu", env=None, state=None, forced_first_action=None,
                     record_observations=False, observation_tape=None):
    """Return aggregate metrics and paired per-episode tensors (never seed replicates).

    Interventions change action selection only; the same environment seed/config is
    reused across conditions. Returned information and actual observations remain
    causally generated by the environment, including intervention-induced changes.
    """
    from .env import ActiveInfoEnv
    cfg = dict(config)
    if response_mode is not None:
        cfg["response_mode"] = response_mode
    if env is None:
        env = ActiveInfoEnv(n_envs, device=device, seed=seed, config=cfg)
        observation = env.reset()
    else:
        observation = env.observation.clone()
        n_envs = observation.shape[0]
    model.eval()
    if state is None:
        state = model.initial_state(n_envs, device)
    horizon = env.episode_length
    start_t = env.t
    generator = torch.Generator(device="cpu").manual_seed(seed+701)
    permutation = torch.randperm(11, generator=generator).to(device)
    time_order = torch.randperm(horizon, generator=generator)
    previous = []
    records = {key: [] for key in ["actions", "oracle_actions", "rewards", "success", "decision_mask", "accepted_calls", "required", "resource_cost", "language_cost", "physical_language_cost", "latency_cost", "wait_action_cost", "delivered", "retention_mask", "habituation_mask", "novelty_mask", "first_stimulus_mask", "renewed_stimulus_mask"]}
    observation_records = []
    called = torch.zeros(n_envs, dtype=torch.bool, device=device)
    if hasattr(env, "called"):
        called = env.called.clone()
    elapsed_start = time.perf_counter()
    for t in range(start_t, horizon):
        if state_mode == "reset_step" or (state_mode == "reset_8" and t % 8 == 0):
            state = model.initial_state(n_envs, device)
        elif state_mode == "noise" and state.numel():
            state = state + torch.randn(state.shape, generator=generator).to(device)*.1
        elif state_mode == "quantize":
            state = torch.round(state*4)/4
        if shortcut == "time_shuffle":
            if observation_tape is None:
                raise ValueError("time_shuffle requires a frozen paired baseline observation tape")
            observed = observation.clone()
            observed[:, :11] = observation_tape[time_order[t], :, :11].to(device)
        else:
            observed = transform_observation(observation, shortcut, t, horizon, generator, permutation, previous)
        if shortcut == "time_shuffle":
            previous.append(observation.clone())
        logits, _, state = model(observed, state)
        action = logits.argmax(-1)
        no_call_logits = logits.clone()
        no_call_logits[:, 5] = -torch.inf
        no_call = no_call_logits.argmax(-1)
        oracle = env.oracle_actions()
        eligible = observation[:, 14] < .5
        if gate == "oracle_policy":
            action = oracle.clone()
        elif gate != "learned":
            action = no_call
            if gate == "always":
                should_call = eligible & ~called
            elif gate == "oracle":
                should_call = eligible & ~called & (oracle == 5)
            elif gate == "random":
                should_call = eligible & ~called & (torch.rand(n_envs, generator=generator).to(device) < 1/max(1,horizon-1))
            elif gate == "matched_rate_random":
                if call_schedule is None:
                    raise ValueError("matched_rate_random requires learned matched_schedule")
                should_call = call_schedule[t].to(device) & eligible & ~called
            elif gate == "never":
                should_call = torch.zeros_like(eligible)
            else:
                raise ValueError(f"unknown gate {gate}")
            action = torch.where(should_call, torch.full_like(action, 5), action)
        if sensing:
            acquisition, mode = sensing
            target_action = {"orient": 2, "observe": 3}[acquisition]
            if mode == "disabled":
                alternate = logits.clone(); alternate[:, target_action] = -torch.inf
                action = torch.where(eligible & (action == target_action), alternate.argmax(-1), action)
            elif mode == "forced":
                action = torch.where(eligible & (t == start_t), torch.full_like(action, target_action), action)
            elif mode == "oracle":
                action = torch.where(eligible & (oracle == target_action), torch.full_like(action, target_action), action)
                alternate = logits.clone(); alternate[:, target_action] = -torch.inf
                action = torch.where(eligible & (oracle != target_action) & (action == target_action), alternate.argmax(-1), action)
            elif mode == "random":
                selected = torch.rand(n_envs, generator=generator).to(device) < 1/max(1,horizon-1)
                alternate = logits.clone(); alternate[:, target_action] = -torch.inf
                action = torch.where(eligible & (action == target_action), alternate.argmax(-1), action)
                action = torch.where(eligible & selected, torch.full_like(action, target_action), action)
        if t == start_t and forced_first_action is not None:
            action = torch.full_like(action, forced_first_action) if isinstance(forced_first_action,int) else forced_first_action.to(device)
        if record_observations:
            observation_records.append(observation.detach().cpu().clone())
        observation, reward, done, info = env.step(action)
        zeros = torch.zeros(n_envs, device=device)
        records["actions"].append(action.detach().cpu())
        records["oracle_actions"].append(oracle.detach().cpu())
        records["rewards"].append(reward.detach().cpu())
        mapping = {"accepted_calls": "call_accepted", "required": "call_required", "delivered": "language_delivered"}
        for key in records:
            if key in ("actions", "oracle_actions", "rewards"):
                continue
            records[key].append(info.get(mapping.get(key,key), zeros).detach().cpu())
        called |= info.get("call_accepted", zeros).bool()
    trace = {key: torch.stack(values) for key,values in records.items()}
    trace["scenario"] = env.scenario.detach().cpu().clone()
    if record_observations:
        trace["observations"] = torch.stack(observation_records)
    metrics = summarize_trace(trace)
    metrics.update(episodes=n_envs,environment_seed=seed,episode_length=horizon,gate=gate,
                   state_mode=state_mode,response_mode=cfg.get("response_mode","correct"),
                   evaluation_seconds=time.perf_counter()-elapsed_start)
    return metrics, trace


def summarize_trace(trace):
    success = (trace["success"].bool() & trace["decision_mask"].bool()).any(0)
    called = trace["accepted_calls"].bool().any(0)
    required = trace["required"].bool().any(0)
    tp = int((called & required).sum()); calls = int(called.sum()); need = int(required.sum())
    recall, precision = fraction(tp, need), fraction(tp,calls)
    f1 = 2*recall*precision/(recall+precision) if recall is not None and precision is not None and recall+precision else 0.
    per_scenario = {}
    for i,name in enumerate(SCENARIOS):
        mask = trace["scenario"] == i
        per_scenario[name] = float(success[mask].float().mean()) if mask.any() else None
    def masked_action(mask_key, desired):
        mask = trace[mask_key].bool()
        return float((trace["actions"][mask] == desired).float().mean()) if mask.any() else None
    first = trace["first_stimulus_mask"].bool()
    repeat = trace["habituation_mask"].bool()
    renewed = trace["renewed_stimulus_mask"].bool()
    habit_env = trace["scenario"] == 4
    habit_ok = ((~first | (trace["actions"] == 2)) & (~repeat | (trace["actions"] == 0)) & (~renewed | (trace["actions"] == 2))).all(0)
    memory = trace["scenario"] == 1
    result = dict(task_success=float(success.float().mean()),scenario_success=per_scenario,
        scenario_macro_success=float(np.mean([x for x in per_scenario.values() if x is not None])),
        reward=float(trace["rewards"].sum(0).mean()),reward_per_step=float(trace["rewards"].mean()),
        llm_call_rate=float(called.float().mean()),accepted_calls=calls,
        required_call_recall=recall,required_call_precision=precision,required_call_f1=f1,
        false_call_rate=fraction(int((called & ~required).sum()),int((~required).sum())),
        missed_required_rate=fraction(int((~called & required).sum()),need),required_episodes=need,
        resource_cost=float(trace["resource_cost"].sum(0).mean()),language_cost=float(trace["language_cost"].sum(0).mean()),
        latency_cost=float(trace["latency_cost"].sum(0).mean()),wait_action_cost=float(trace["wait_action_cost"].sum(0).mean()),
        physical_language_cost=float(trace["physical_language_cost"].sum(0).mean()),
        memory_retention=float(success[memory].float().mean()) if memory.any() else None,
        habituation_sequence_success=float(habit_ok[habit_env].float().mean()) if habit_env.any() else None,
        habituation_ignore_rate=masked_action("habituation_mask",0),novelty_reaction=masked_action("novelty_mask",2))
    call_time = trace["accepted_calls"].float().argmax(0)
    delivered = trace["delivered"].bool().any(0)
    delivery_time = trace["delivered"].float().argmax(0)
    result["language_latency_steps"] = float((delivery_time[called & delivered]-call_time[called & delivered]+1).float().mean()) if (called & delivered).any() else None
    result["language_response_delivery_rate"] = fraction(int((called&delivered).sum()),calls)
    result.update(action_metrics(trace["actions"],trace["oracle_actions"]))
    return result


def load_checkpoint(path, device="cpu"):
    from experiments.k0_brainstem.models import make_model
    checkpoint = torch.load(path, map_location=device, weights_only=False)
    config = checkpoint["config"]
    model = make_model(config["architecture"], hidden_size=config.get("hidden_size",128), density=config.get("density",.1)).to(device)
    model.load_state_dict(checkpoint["model"])
    model.eval()
    return model, checkpoint


@torch.no_grad()
def cpu_benchmark(model, warmup=30, repeats=200, threads=4):
    import copy
    cpu_model = copy.deepcopy(model).cpu().eval()
    old_threads = torch.get_num_threads()
    torch.set_num_threads(threads)
    obs = torch.full((1,16), .5)
    state = cpu_model.initial_state(1,"cpu")
    try:
        for _ in range(warmup):
            _,_,state = cpu_model(obs,state)
        durations=[]
        for _ in range(repeats):
            start=time.perf_counter_ns(); _,_,state=cpu_model(obs,state)
            durations.append((time.perf_counter_ns()-start)/1e6)
    finally:
        torch.set_num_threads(old_threads)
    return {"cpu_inference_ms_mean":float(np.mean(durations)),"cpu_inference_ms_median":float(np.median(durations)),
            "cpu_inference_ms_p95":float(np.percentile(durations,95)),"cpu_benchmark_batch":1,
            "cpu_benchmark_threads":threads,"cpu_benchmark_repeats":repeats,
            "cpu_benchmark_host":os.uname().nodename}


def state_equal(left,right):
    if isinstance(left,torch.Tensor):return isinstance(right,torch.Tensor) and torch.equal(left,right)
    if isinstance(left,dict):return isinstance(right,dict) and left.keys()==right.keys() and all(state_equal(left[k],right[k]) for k in left)
    if isinstance(left,(tuple,list)):return type(left)==type(right) and len(left)==len(right) and all(state_equal(a,b) for a,b in zip(left,right))
    return left==right


@torch.no_grad()
def counterfactual(model, config, n_envs=256, seed=900001, device="cpu"):
    """Identical pre-treatment world + hidden state; one CALL vs one NO CALL.

    Future calls are disabled in both arms to isolate the one information
    acquisition. This is a forced-call causal estimand, not learned-gate ATE.
    """
    from .env import ActiveInfoEnv
    cfg={**config,"scenario":"language"}
    env=ActiveInfoEnv(n_envs,device,seed,cfg);obs=env.reset()
    state=model.initial_state(n_envs,device)
    # A common no-call prefix creates a nontrivial recurrent state before fork.
    logits,_,state=model(obs,state);logits[:,5]=-torch.inf
    obs,_,_,_=env.step(logits.argmax(-1))
    fork=env.snapshot();state_before=state.clone()
    logits,_,_=model(obs,state_before.clone());logits[:,5]=-torch.inf
    no_call=logits.argmax(-1)
    call_env,no_env=env.clone(),env.clone()
    identical_env=state_equal(call_env.snapshot(),no_env.snapshot())
    call_metrics,call=evaluate_episode(model,cfg,n_envs,seed,gate="never",device=device,env=call_env,state=state_before.clone(),forced_first_action=5)
    no_metrics,no=evaluate_episode(model,cfg,n_envs,seed,gate="never",device=device,env=no_env,state=state_before.clone(),forced_first_action=no_call)
    delta_reward=call["rewards"].sum(0)-no["rewards"].sum(0)
    delta_success=call["success"].bool().any(0).float()-no["success"].bool().any(0).float()
    downstream=(call["actions"][1:]!=no["actions"][1:]).float()
    # Waiting steps are an outcome of the branch, while acquisition delay is a service condition.
    wait_delta=(call["actions"]==1).sum(0)-(no["actions"]==1).sum(0)
    return {"estimand":"single_forced_call_at_step_1_vs_no_call_future_calls_disabled",
        "episodes":n_envs,"environment_seed":seed,"fork_step":1,
        "identical_model_state_at_fork":bool(torch.equal(state,state_before)),
        "identical_environment_state_at_fork":identical_env,
        "delta_reward":float(delta_reward.mean()),"delta_success":float(delta_success.mean()),
        "delta_latency_wait_steps":float(wait_delta.float().mean()),
        "delta_language_latency_steps":call_metrics["language_latency_steps"],
        "delta_episode_duration_steps":0,
        "delta_downstream_action_rate":float(downstream.mean()),
        "delta_final_action_rate":float((call["actions"][-1]!=no["actions"][-1]).float().mean()),
        "call":call_metrics,"no_call":no_metrics,
        "paired_episode_delta_reward":delta_reward.tolist(),"paired_episode_delta_success":delta_success.tolist()}


@torch.no_grad()
def ambiguity_audit(model, config, n_envs=256, seed=900001, device="cpu"):
    from .env import ActiveInfoEnv
    cfg={**config,"scenario":"language"}
    env_a=ActiveInfoEnv(n_envs,device,seed,cfg);env_b=ActiveInfoEnv(n_envs,device,seed,cfg)
    env_a.reset(torch.zeros(n_envs,dtype=torch.long,device=device))
    env_b.reset(torch.ones(n_envs,dtype=torch.long,device=device))
    a,ta=evaluate_episode(model,cfg,n_envs,seed,gate="never",env=env_a,device=device,record_observations=True)
    b,tb=evaluate_episode(model,cfg,n_envs,seed,gate="never",env=env_b,device=device,record_observations=True)
    exact=bool(torch.equal(ta["observations"],tb["observations"]))
    identical_actions=bool(torch.equal(ta["actions"],tb["actions"]))
    paired_success=(a["task_success"]+b["task_success"])/2
    return {"episodes_per_latent":n_envs,"environment_seed":seed,"bit_identical_no_call_history":exact,
        "identical_no_call_actions":identical_actions,"balanced_latent_success":paired_success,
        "bayes_ceiling":.5,"passed":exact and identical_actions and paired_success<=.5+1e-8,
        "interpretation":"Post-call MLP success is expected; leakage criterion applies before/without language information."}


def seed_statistics(values, bootstrap_samples=4000):
    array=np.asarray([v for v in values if v is not None and np.isfinite(v)],dtype=float)
    if not len(array):return {"n_seeds":0,"mean":None,"sd":None,"median":None,"ci95":None}
    rng=np.random.default_rng(314159)
    means=rng.choice(array,size=(bootstrap_samples,len(array)),replace=True).mean(1)
    return {"n_seeds":len(array),"mean":float(array.mean()),"sd":float(array.std(ddof=1)) if len(array)>1 else None,
            "median":float(np.median(array)),"ci95":[float(x) for x in np.percentile(means,[2.5,97.5])]}


def paired_sign_test(differences):
    nonzero=[float(x) for x in differences if x is not None and abs(x)>1e-12]
    n=len(nonzero);positive=sum(x>0 for x in nonzero);k=min(positive,n-positive)
    probability=min(1.,2*sum(math.comb(n,i) for i in range(k+1))/2**n) if n else 1.
    return {"n_nonzero_seeds":n,"positive":positive,"negative":n-positive,"two_sided_exact_p":probability}


def evaluate_checkpoint(path, output_root, n_envs=256, long_envs=64, basic_only=False,
                        evaluation_seed=900001, device="cpu", resume=True):
    path=Path(path);output_root=Path(output_root)
    model,checkpoint=load_checkpoint(path,device)
    training_config=checkpoint["config"]
    cfg={**training_config.get("env",{}),"mix_conditions":False,"language_cost":.05,
         "language_reliability":1.,"language_latency":2,"response_mode":"correct","ood":None}
    cfg.pop("scenario",None)
    name=path.parent.name+"__"+path.stem
    directory=output_root/"evaluations"/name
    meta={"run_id":path.parent.name,"checkpoint_name":path.name,"architecture":training_config["architecture"],
          "seed":int(training_config["seed"]),"stage":checkpoint["stage"],"update":checkpoint["update"],
          "checkpoint_sha256":hashlib.sha256(path.read_bytes()).hexdigest(),"environment_seed":evaluation_seed,
          "evaluation_protocol":{"num_envs":n_envs,"long_envs":long_envs,"config":cfg,"version":1}}
    identity_inputs={"checkpoint_sha256":meta["checkpoint_sha256"],"seed":evaluation_seed,
        "num_envs":n_envs,"long_envs":long_envs,"environment":cfg,
        "grids":{"cost":COSTS,"reliability":RELIABILITIES,"latency":LATENCIES,"delay":DELAYS,"response":RESPONSES,"ood":OOD_MODES,"states":STATES},
        "source_sha256":{name:hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest() for name in ["evaluate.py","env.py"]}}
    identity=hashlib.sha256(json.dumps(identity_inputs,sort_keys=True).encode()).hexdigest()
    meta["evaluation_identity"]=identity
    identity_path=directory/"identity.json"
    if identity_path.exists() and json.loads(identity_path.read_text()).get("evaluation_identity")!=identity:
        raise ValueError(f"Evaluation identity changed; preserve existing evidence and use a new --artifacts directory: {directory}")
    atomic_json(identity_path,{"evaluation_identity":identity,"inputs":identity_inputs})
    def eval_one(**kwargs):
        config={**cfg,**kwargs.pop("config",{})}
        return evaluate_episode(model,config,n_envs=kwargs.pop("n_envs",n_envs),seed=evaluation_seed,device=device,**kwargs)
    def category(category_name,work):
        target=directory/(category_name+".json")
        if resume and target.exists():
            previous=json.loads(target.read_text())
            if previous.get("complete") and previous.get("checkpoint_sha256")==meta["checkpoint_sha256"] and previous.get("evaluation_identity")==identity:
                return previous["records"]
        records=[]
        for condition,details,result in work():
            records.append({**meta,"category":category_name,"condition":condition,**details,"metrics":result})
            atomic_json(target,{**meta,"complete":False,"records":records})
        atomic_json(target,{**meta,"complete":True,"records":records})
        return records
    baseline, learned_trace=eval_one(record_observations=True)
    oracle,_=eval_one(gate="oracle_policy")
    baseline["oracle_reward"]=oracle["reward"];baseline["oracle_regret"]=oracle["reward"]-baseline["reward"]
    baseline["oracle_call_rate"]=oracle["llm_call_rate"]
    baseline["oracle_sensing_rate"]=oracle["orient_rate"]+oracle["observe_rate"]
    stats=model.stats() if hasattr(model,"stats") else {"params":sum(p.numel() for p in model.parameters())}
    main={**meta,**baseline,**stats,**cpu_benchmark(model),"complete":True,"environment_config":cfg,
          "unit":"one independent training seed; episodes are paired evaluation observations"}
    training_rows=[]
    metrics_path=path.parent/"metrics.jsonl"
    if metrics_path.exists():
        for line in metrics_path.read_text().splitlines():
            try:training_rows.append(json.loads(line))
            except ValueError:pass
    throughput=[r["steps_per_second"] for r in training_rows if r.get("steps_per_second") is not None]
    main["training_steps_per_second_mean"]=float(np.mean(throughput)) if throughput else None
    main["training_wall_seconds"]=float(sum(r.get("elapsed",0) for r in training_rows)) if training_rows else None
    main["estimated_compute_proxy_active_connections"]=stats.get("active_connections")
    main["compute_proxy_note"]="Logical active connections per model forward, not measured FLOPs or physical sparse speedup."
    atomic_json(directory/"main.json",main)
    if basic_only:
        return main
    def voi_work():
        for dimension,values,key in [("cost",COSTS,"language_cost"),("reliability",RELIABILITIES,"language_reliability"),("latency",LATENCIES,"language_latency")]:
            for value in values:
                config={key:value};m,_=eval_one(config=config);o,_=eval_one(config=config,gate="oracle_policy")
                m.update(oracle_reward=o["reward"],oracle_regret=o["reward"]-m["reward"],oracle_call_rate=o["llm_call_rate"])
                yield f"{dimension}={value}",{"dimension":dimension,"value":value,"threshold_extension":dimension=="cost" and value>.4},m
    category("voi_results",voi_work)
    def policy_work():
        schedule=matched_schedule(learned_trace,evaluation_seed+902)
        for gate in GATES:
            m,_=eval_one(gate=gate,call_schedule=schedule if gate=="matched_rate_random" else None)
            if gate=="matched_rate_random":
                m["matched_accepted_calls_exact"]=m["accepted_calls"]==baseline["accepted_calls"]
                if not m["matched_accepted_calls_exact"]:
                    raise AssertionError("matched-rate random accepted call count mismatch")
                m["matched_reference_accepted_calls"]=baseline["accepted_calls"]
            yield gate,{},m
    category("policy_interventions",policy_work)
    category("language_response_ablation",lambda:((mode,{},eval_one(response_mode=mode)[0]) for mode in RESPONSES))
    category("counterfactual",lambda:iter([("call_vs_no_call",{},counterfactual(model,cfg,n_envs,evaluation_seed,device))]))
    category("ambiguity_audit",lambda:iter([("paired_no_call",{},ambiguity_audit(model,cfg,n_envs,evaluation_seed,device))]))
    def sensing_work():
        for acquisition in ["orient","observe"]:
            for mode in ["learned","forced","disabled","oracle","random"]:
                metrics,_=eval_one(config={"scenario":acquisition},sensing=(acquisition,mode))
                yield acquisition+"/"+mode,{"acquisition":acquisition,"mode":mode},metrics
    category("active_sensing",sensing_work)
    def retention_work():
        for delay in DELAYS:
            for mode in STATES:
                metrics,_=eval_one(config={"scenario":"memory","memory_delay":delay,"strict_memory":True},n_envs=long_envs,state_mode=mode)
                yield f"{delay}/{mode}",{"delay":delay,"state_mode":mode,"long_delay_episode_limit":long_envs},metrics
    category("retention_results",retention_work)
    category("ood_results",lambda:((mode,{},eval_one(config={"ood":mode})[0]) for mode in OOD_MODES))
    def habituation_work():
        for dimension,values in [("novelty_strength",[.2,.5,.95]),("repeat_count",[1,3,6]),("habituation_gap",[1,3,6]),("noise",[0,.15,.5])]:
            for value in values:
                metrics,_=eval_one(config={"scenario":"habituation",dimension:value})
                yield f"{dimension}={value}",{"dimension":dimension,"value":value},metrics
    category("habituation_results",habituation_work)
    def shortcut_work():
        conditions=["channel_shuffle","time_shuffle","cue_mask","latent_correlated_removal","prefix_removal","suffix_removal"]+[f"mask_{i}" for i in range(16)]
        for mode in conditions:
            metrics,_=eval_one(shortcut=mode,observation_tape=learned_trace["observations"] if mode=="time_shuffle" else None)
            yield mode,{"diagnostic_only":True,"trigger":"prespecified all runs, including success below 99%",
                        "frozen_observation_replay":mode=="time_shuffle","noncausal_diagnostic":mode=="time_shuffle",
                        "public_protocol_corrupted":mode in [f"mask_{i}" for i in range(11,16)],
                        "note":"time permutation uses baseline sensor tape, can expose future information; not causal evidence. Channels 11:16 stay current except explicit individual masks."},metrics
    category("shortcut_audit",shortcut_work)
    atomic_json(directory/"complete.json",{**meta,"complete":True,"basic_only":False,"categories":10})
    return main


def consolidate(output_root):
    root=Path(output_root)
    main=[json.loads(p.read_text()) for p in sorted((root/"evaluations").glob("*/main.json"))]
    atomic_json(root/"run_summary.json",main)
    import csv
    fields=["run_id","checkpoint_name","architecture","seed","stage","task_success","scenario_macro_success","reward","oracle_regret","llm_call_rate","required_call_recall","required_call_precision","required_call_f1","false_call_rate","missed_required_rate","action_macro_f1","action_entropy_nats","resource_cost","language_cost","language_latency_steps","memory_retention","habituation_sequence_success","novelty_reaction","params","active_connections","gates","cpu_inference_ms_mean","cpu_inference_ms_median","cpu_inference_ms_p95"]
    with (root/"run_summary.csv").open("w",newline="") as stream:
        writer=csv.DictWriter(stream,fieldnames=fields,extrasaction="ignore",lineterminator="\n");writer.writeheader();writer.writerows(main)
    for category_name in ["voi_results","policy_interventions","language_response_ablation","counterfactual","ambiguity_audit","active_sensing","retention_results","ood_results","habituation_results","shortcut_audit"]:
        records=[]
        for path in sorted((root/"evaluations").glob("*/"+category_name+".json")):
            content=json.loads(path.read_text())
            if content.get("complete"):records.extend(content["records"])
        atomic_json(root/(category_name+".json"),records)
    arms=[record for record in main if record["architecture"]=="gru128"]
    atomic_json(root/"ppo_ablation.json",arms)
    statistics={}
    for arch in sorted({r["architecture"] for r in main}):
        selected=[r for r in main if r["architecture"]==arch and r["checkpoint_name"]=="imitation_best.pt"]
        statistics[arch]={key:seed_statistics([r.get(key) for r in selected]) for key in ["task_success","reward","llm_call_rate","memory_retention","action_macro_f1","cpu_inference_ms_median"]}
    atomic_json(root/"seed_statistics.json",statistics)
    contrasts=[]
    def paired_category(filename,left,right,metric):
        records=json.loads((root/filename).read_text())
        for arch in ARCHITECTURES:
            def outcome(record):
                current=record["metrics"]
                for part in metric.split("."):
                    if current is None:return None
                    current=current.get(part)
                return current
            a={r["seed"]:outcome(r) for r in records if r["architecture"]==arch and r["condition"]==left}
            b={r["seed"]:outcome(r) for r in records if r["architecture"]==arch and r["condition"]==right}
            seeds=sorted(seed for seed in set(a)&set(b) if a[seed] is not None and b[seed] is not None)
            differences=[a[seed]-b[seed] for seed in seeds]
            contrasts.append({"architecture":arch,"source":filename,"left":left,"right":right,"metric":metric,
                              "seed_ids":seeds,"seed_paired_differences":differences,
                              "difference_statistics":seed_statistics(differences),"exact_sign_test":paired_sign_test(differences)})
    for metric in ["task_success","scenario_success.language","reward"]:
        paired_category("policy_interventions.json","learned","never",metric)
        paired_category("policy_interventions.json","learned","matched_rate_random",metric)
        paired_category("language_response_ablation.json","correct","shuffled",metric)
        paired_category("language_response_ablation.json","correct","missing",metric)
    for acquisition in ["orient","observe"]:
        paired_category("active_sensing.json",acquisition+"/learned",acquisition+"/disabled","task_success")
    for arm in ["B1","B2","B3","B4","B5","B6","B7"]:
        for reference in ["B0","B1"]:
            if reference==arm:continue
            for metric in ["task_success","reward","llm_call_rate"]:
                selected=[r for r in main if r["architecture"]=="gru128" and (r["checkpoint_name"]=="imitation_best.pt" or r["checkpoint_name"]=="ppo_final.pt")]
                a={r["seed"]:r.get(metric) for r in selected if r["run_id"].endswith("-"+arm)}
                b={r["seed"]:r.get(metric) for r in selected if r["run_id"].endswith("-"+reference)}
                seeds=sorted(seed for seed in set(a)&set(b) if a[seed] is not None and b[seed] is not None)
                differences=[a[seed]-b[seed] for seed in seeds]
                contrasts.append({"architecture":"gru128","source":"ppo_ablation.json","left":arm,"right":reference,"metric":metric,
                                  "seed_ids":seeds,"seed_paired_differences":differences,"difference_statistics":seed_statistics(differences),
                                  "exact_sign_test":paired_sign_test(differences)})
    atomic_json(root/"paired_comparisons.json",contrasts)
    retention=json.loads((root/"retention_results.json").read_text());horizons={}
    for arch in ARCHITECTURES:
        rows=[r for r in retention if r["architecture"]==arch and r["state_mode"]=="normal"]
        delays=sorted({r["delay"] for r in rows})
        curve={str(delay):seed_statistics([r["metrics"].get("memory_retention") for r in rows if r["delay"]==delay]) for delay in delays}
        below=[delay for delay in delays if curve[str(delay)]["mean"] is not None and curve[str(delay)]["mean"]<=.5]
        includes_chance=[delay for delay in delays if curve[str(delay)]["ci95"] and curve[str(delay)]["ci95"][0]<=.5]
        horizons[arch]={"curve":curve,"first_tested_delay_mean_at_or_below_chance":min(below) if below else None,
                        "first_tested_delay_ci_lower_at_or_below_chance":min(includes_chance) if includes_chance else None,
                        "interpretation":"Discrete tested-delay crossing only; absence is right-censoring, not infinite memory."}
    atomic_json(root/"retention_horizon.json",horizons)
    return main


def main():
    parser=argparse.ArgumentParser(description="Finite seed-paired K0-E2 evaluation")
    parser.add_argument("--checkpoint")
    parser.add_argument("--artifacts",required=True)
    parser.add_argument("--num-envs",type=int,default=256)
    parser.add_argument("--long-envs",type=int,default=64)
    parser.add_argument("--seed",type=int,default=900001)
    parser.add_argument("--device",default="cpu")
    parser.add_argument("--threads",type=int,default=4)
    parser.add_argument("--basic-only",action="store_true")
    parser.add_argument("--all",action="store_true")
    parser.add_argument("--consolidate-only",action="store_true")
    args=parser.parse_args();torch.set_num_threads(args.threads)
    if args.checkpoint:
        evaluate_checkpoint(args.checkpoint,args.artifacts,args.num_envs,args.long_envs,args.basic_only,args.seed,args.device)
    elif args.all:
        root=Path(args.artifacts)
        checkpoints=list(sorted(root.glob("runs/*-B0/imitation_best.pt")))
        checkpoints+=list(sorted(root.glob("runs/*-B[1-7]/ppo_final.pt")))
        for checkpoint in checkpoints:
            basic=checkpoint.name!="imitation_best.pt"
            print(f"Evaluating {checkpoint.parent.name}/{checkpoint.name} basic={basic}",flush=True)
            evaluate_checkpoint(checkpoint,root,args.num_envs,args.long_envs,basic,args.seed,args.device)
    elif not args.consolidate_only:
        parser.error("provide --checkpoint, --all, or --consolidate-only")
    consolidate(args.artifacts)


if __name__=="__main__":main()
